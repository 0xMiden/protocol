//! Generation of the checked-in per-note consumption cost tables.
//!
//! The cost of a note is the total cycle count of the canonical network-account transaction
//! consuming it, taken as the maximum across the note's benchmark scenarios (one per execution
//! path). [`update_cost_tables`] renders the measured cycle counts as `pub const` items into
//! the generated table files in `miden-standards` and `miden-agglayer`.

use std::collections::BTreeMap;
use std::path::PathBuf;

use anyhow::{Context, Result};
use miden_agglayer::AgglayerNote;
use miden_protocol::note::NoteScriptRoot;
use miden_standards::note::StandardNote;
use miden_standards::note::costs::NoteCost;

#[cfg(test)]
use crate::context_setups::build_benchmark_context;
use crate::cycle_counting_benchmarks::ExecutionBenchmark;

/// Header line of the generated table files.
const GENERATED_HEADER: &str = "// This file is @generated by `make update-note-costs`. Do not edit by hand.\n\
// Values are maxima across the benchmarked paths; see `miden_standards::note::costs` for the\n\
// caveats on what they do and do not cover.\n";

/// Notes priced in the checked-in cost tables, with their contributing benchmark scenarios.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PricedNote {
    Standard(StandardNote),
    Agglayer(AgglayerNote),
}

impl PricedNote {
    /// All priced notes, in the order their constants appear in the generated tables.
    ///
    /// TX_FEE is deliberately absent: it is consumed by fee-collecting operators, not by
    /// network accounts, and has no cost table entry.
    pub const fn all() -> &'static [PricedNote] {
        &[
            PricedNote::Standard(StandardNote::P2ID),
            PricedNote::Standard(StandardNote::P2IDE),
            PricedNote::Standard(StandardNote::SWAP),
            PricedNote::Standard(StandardNote::PSWAP),
            PricedNote::Standard(StandardNote::MINT),
            PricedNote::Standard(StandardNote::BURN),
            PricedNote::Standard(StandardNote::CONSTANT_FEE_POLICY_CONFIG),
            PricedNote::Standard(StandardNote::FAUCET_POLICY_CONFIG),
            PricedNote::Standard(StandardNote::FAUCET_METADATA_CONFIG),
            PricedNote::Standard(StandardNote::MIN_BURN_AMOUNT_CONFIG),
            PricedNote::Standard(StandardNote::ALLOWLIST_CONFIG),
            PricedNote::Standard(StandardNote::BLOCKLIST_CONFIG),
            PricedNote::Standard(StandardNote::PAUSE_CONFIG),
            PricedNote::Standard(StandardNote::OWNER_CONFIG),
            PricedNote::Standard(StandardNote::RBAC_CONFIG),
            PricedNote::Standard(StandardNote::NETWORK_ACCOUNT_CONFIG),
            PricedNote::Standard(StandardNote::FEE_SPONSORSHIP),
            PricedNote::Agglayer(AgglayerNote::CLAIM),
            PricedNote::Agglayer(AgglayerNote::B2AGG),
            PricedNote::Agglayer(AgglayerNote::CONFIG_AGG_BRIDGE),
            PricedNote::Agglayer(AgglayerNote::DEREGISTER_AGG_FAUCET),
            PricedNote::Agglayer(AgglayerNote::UPDATE_GER),
            PricedNote::Agglayer(AgglayerNote::REMOVE_GER),
        ]
    }

    /// Benchmark scenarios whose maximum total cycle count defines this note's cost.
    /// (Not `const`: the TX_FEE `unreachable!` message is not const-callable.)
    pub fn scenarios(&self) -> &'static [ExecutionBenchmark] {
        match self {
            PricedNote::Standard(StandardNote::P2ID) => &[
                ExecutionBenchmark::ConsumeP2idNetwork,
                ExecutionBenchmark::ConsumeP2idMaxAssetsNetwork,
            ],
            // The 16-asset variant runs the claim path: reclaim adds only a constant ~150
            // cycles over claim, which the per-asset cost dwarfs.
            PricedNote::Standard(StandardNote::P2IDE) => &[
                ExecutionBenchmark::ConsumeP2ideClaimNetwork,
                ExecutionBenchmark::ConsumeP2ideMaxAssetsNetwork,
                ExecutionBenchmark::ConsumeP2ideReclaimNetwork,
            ],
            PricedNote::Standard(StandardNote::SWAP) => &[
                ExecutionBenchmark::ConsumeSwapPublicPaybackNetwork,
                ExecutionBenchmark::ConsumeSwapPrivatePaybackNetwork,
            ],
            PricedNote::Standard(StandardNote::PSWAP) => &[
                ExecutionBenchmark::ConsumePswapFullFillNetwork,
                ExecutionBenchmark::ConsumePswapPartialFillNetwork,
            ],
            PricedNote::Standard(StandardNote::MINT) => &[
                ExecutionBenchmark::ConsumeMintFungibleNetwork,
                ExecutionBenchmark::ConsumeMintNonFungibleNetwork,
            ],
            PricedNote::Standard(StandardNote::BURN) => &[ExecutionBenchmark::ConsumeBurnNetwork],
            PricedNote::Standard(StandardNote::CONSTANT_FEE_POLICY_CONFIG) => {
                &[ExecutionBenchmark::ConsumeConstantFeePolicyConfigNetwork]
            },
            PricedNote::Standard(StandardNote::FAUCET_POLICY_CONFIG) => {
                &[ExecutionBenchmark::ConsumeFaucetPolicyConfigNetwork]
            },
            PricedNote::Standard(StandardNote::FAUCET_METADATA_CONFIG) => {
                &[ExecutionBenchmark::ConsumeFaucetMetadataConfigNetwork]
            },
            PricedNote::Standard(StandardNote::MIN_BURN_AMOUNT_CONFIG) => {
                &[ExecutionBenchmark::ConsumeMinBurnAmountConfigNetwork]
            },
            PricedNote::Standard(StandardNote::ALLOWLIST_CONFIG) => {
                &[ExecutionBenchmark::ConsumeAllowlistConfigNetwork]
            },
            PricedNote::Standard(StandardNote::BLOCKLIST_CONFIG) => {
                &[ExecutionBenchmark::ConsumeBlocklistConfigNetwork]
            },
            PricedNote::Standard(StandardNote::PAUSE_CONFIG) => {
                &[ExecutionBenchmark::ConsumePauseConfigNetwork]
            },
            PricedNote::Standard(StandardNote::OWNER_CONFIG) => {
                &[ExecutionBenchmark::ConsumeOwnerConfigNetwork]
            },
            PricedNote::Standard(StandardNote::RBAC_CONFIG) => {
                &[ExecutionBenchmark::ConsumeRbacConfigNetwork]
            },
            PricedNote::Standard(StandardNote::NETWORK_ACCOUNT_CONFIG) => {
                &[ExecutionBenchmark::ConsumeNetworkAccountConfigNetwork]
            },
            PricedNote::Standard(StandardNote::FEE_SPONSORSHIP) => {
                &[ExecutionBenchmark::ConsumeFeeSponsorshipWithFeatureNetwork]
            },
            PricedNote::Standard(StandardNote::TX_FEE) => {
                unreachable!("TX_FEE is not priced and never appears in `all()`")
            },
            PricedNote::Agglayer(AgglayerNote::CLAIM) => &[
                ExecutionBenchmark::ConsumeClaimL1WithFee,
                ExecutionBenchmark::ConsumeClaimL2WithFee,
            ],
            PricedNote::Agglayer(AgglayerNote::B2AGG) => &[
                ExecutionBenchmark::ConsumeB2AggWithFee,
                ExecutionBenchmark::ConsumeB2AggPopulatedWithFee,
            ],
            PricedNote::Agglayer(AgglayerNote::CONFIG_AGG_BRIDGE) => {
                &[ExecutionBenchmark::ConsumeConfigAggBridgeWithFee]
            },
            PricedNote::Agglayer(AgglayerNote::DEREGISTER_AGG_FAUCET) => {
                &[ExecutionBenchmark::ConsumeDeregisterAggFaucetWithFee]
            },
            PricedNote::Agglayer(AgglayerNote::UPDATE_GER) => {
                &[ExecutionBenchmark::ConsumeUpdateGerWithFee]
            },
            PricedNote::Agglayer(AgglayerNote::REMOVE_GER) => {
                &[ExecutionBenchmark::ConsumeRemoveGerWithFee]
            },
        }
    }

    /// The note's script root.
    fn script_root(&self) -> NoteScriptRoot {
        match self {
            PricedNote::Standard(note) => note.script_root(),
            PricedNote::Agglayer(note) => note.script_root(),
        }
    }

    /// The compiled-in cost of this note, read from its own crate's lookup.
    fn note_cost(&self) -> NoteCost {
        let root = self.script_root();
        match self {
            PricedNote::Standard(_) => StandardNote::note_cost(root),
            PricedNote::Agglayer(_) => AgglayerNote::note_cost(root),
        }
        .expect("every priced note has a checked-in cost")
    }

    /// The compiled-in cost constant for this note.
    pub fn committed_cycles(&self) -> u32 {
        self.note_cost().cycles()
    }

    /// The note's name (e.g. "P2ID").
    fn name(&self) -> &'static str {
        match self {
            PricedNote::Standard(note) => note.name(),
            PricedNote::Agglayer(note) => note.name(),
        }
    }

    /// The cost constant's name in the generated table.
    fn table_const_name(&self) -> String {
        format!("{}_CONSUMPTION_CYCLES", self.name())
    }

    /// The note's name with its indefinite article, as used in the generated doc comment.
    fn doc_subject(&self) -> String {
        format!("{} {}", self.doc_article(), self.name())
    }

    /// The indefinite article of the note's name, kept as explicit data: no first-letter
    /// heuristic separates the leading vowel sounds ("an RBAC", read letter by letter) from the
    /// consonant sounds ("a REMOVE_GER", read as a word).
    fn doc_article(&self) -> &'static str {
        match self {
            PricedNote::Standard(
                StandardNote::ALLOWLIST_CONFIG
                | StandardNote::OWNER_CONFIG
                | StandardNote::RBAC_CONFIG,
            )
            | PricedNote::Agglayer(AgglayerNote::UPDATE_GER) => "an",
            _ => "a",
        }
    }

    /// Whether the constant lives in the `miden-agglayer` table (as opposed to the
    /// `miden-standards` one).
    const fn is_agglayer(&self) -> bool {
        matches!(self, PricedNote::Agglayer(_))
    }
}

/// Short label of the execution path a scenario benchmarks, used in the generated table docs
/// of notes with more than one benchmarked path.
fn path_label(bench: ExecutionBenchmark) -> &'static str {
    match bench {
        ExecutionBenchmark::ConsumeP2idNetwork => "1 asset",
        ExecutionBenchmark::ConsumeP2idMaxAssetsNetwork => "16 assets",
        ExecutionBenchmark::ConsumeP2ideClaimNetwork => "claim",
        ExecutionBenchmark::ConsumeP2ideMaxAssetsNetwork => "claim with 16 assets",
        ExecutionBenchmark::ConsumeP2ideReclaimNetwork => "reclaim",
        ExecutionBenchmark::ConsumeSwapPublicPaybackNetwork => "public payback",
        ExecutionBenchmark::ConsumeSwapPrivatePaybackNetwork => "private payback",
        ExecutionBenchmark::ConsumePswapFullFillNetwork => "full fill",
        ExecutionBenchmark::ConsumePswapPartialFillNetwork => "partial fill",
        ExecutionBenchmark::ConsumeMintFungibleNetwork => "fungible faucet",
        ExecutionBenchmark::ConsumeMintNonFungibleNetwork => "non-fungible faucet",
        ExecutionBenchmark::ConsumeFeeSponsorshipWithFeatureNetwork => "with feature note",
        ExecutionBenchmark::ConsumeFeeSponsorshipReclaim => "reclaim",
        ExecutionBenchmark::ConsumeClaimL1WithFee => "L1 origin",
        ExecutionBenchmark::ConsumeClaimL2WithFee => "L2 origin",
        ExecutionBenchmark::ConsumeB2AggWithFee => "empty frontier",
        ExecutionBenchmark::ConsumeB2AggPopulatedWithFee => "2^31-1 leaves",
        _ => unreachable!("only scenarios of multi-path priced notes have path labels"),
    }
}

/// Executes the note's benchmark scenarios and returns each scenario's total cycle count.
#[cfg(test)]
async fn benched_path_cycles(note: PricedNote) -> Result<Vec<(ExecutionBenchmark, u32)>> {
    let mut path_cycles = Vec::new();
    for &bench in note.scenarios() {
        let mock_tx = build_benchmark_context(bench)
            .await
            .with_context(|| format!("failed to build mock transaction for `{bench}`"))?;
        let executed = mock_tx
            .execute()
            .await
            .with_context(|| format!("failed to execute transaction for `{bench}`"))?;
        let cycles = u32::try_from(executed.measurements().total_cycles())
            .context("total cycle count does not fit into u32")?;
        path_cycles.push((bench, cycles));
    }
    Ok(path_cycles)
}

/// Executes the note's benchmark scenarios and returns the maximum total cycle count.
#[cfg(test)]
async fn benched_cycles(note: PricedNote) -> Result<u32> {
    let max_cycles = benched_path_cycles(note)
        .await?
        .into_iter()
        .map(|(_, cycles)| cycles)
        .max()
        .expect("every priced note has at least one scenario");
    Ok(max_cycles)
}

/// Rewrites the two generated cost table files from the given per-scenario cycle counts
/// (typically the measurements the benchmark run just collected, so nothing is executed
/// twice).
pub fn update_cost_tables(measured: &BTreeMap<ExecutionBenchmark, u32>) -> Result<()> {
    let mut standards_table = String::from(GENERATED_HEADER);
    let mut agglayer_table = String::from(GENERATED_HEADER);

    for &note in PricedNote::all() {
        let path_cycles: Vec<(ExecutionBenchmark, u32)> = note
            .scenarios()
            .iter()
            .map(|&bench| {
                measured
                    .get(&bench)
                    .copied()
                    .map(|cycles| (bench, cycles))
                    .with_context(|| format!("missing measurement for `{bench}`"))
            })
            .collect::<Result<_>>()?;
        let cycles = path_cycles
            .iter()
            .map(|(_, cycles)| *cycles)
            .max()
            .expect("every priced note has at least one scenario");

        let doc = if path_cycles.len() == 1 {
            format!(
                "/// Cycles of consuming {} note (single benchmarked path).",
                note.doc_subject()
            )
        } else {
            let max_position = path_cycles
                .iter()
                .position(|(_, path)| *path == cycles)
                .expect("the maximum comes from one of the paths");
            let paths = path_cycles
                .iter()
                .enumerate()
                .map(|(position, (bench, path))| {
                    let marker = if position == max_position { " (maximum)" } else { "" };
                    format!("{} {path}{marker}", path_label(*bench))
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("/// Cycles of consuming {} note: {paths}.", note.doc_subject())
        };

        let table = if note.is_agglayer() {
            &mut agglayer_table
        } else {
            &mut standards_table
        };
        table.push_str(&format!(
            "\n{doc}\npub const {}: u32 = {};\n",
            note.table_const_name(),
            cycles,
        ));
    }

    let standards_path = table_path("miden-standards/src/note/costs/table.rs");
    std::fs::write(&standards_path, standards_table)
        .with_context(|| format!("failed to write `{}`", standards_path.display()))?;

    let agglayer_path = table_path("miden-agglayer/src/costs/table.rs");
    std::fs::write(&agglayer_path, agglayer_table)
        .with_context(|| format!("failed to write `{}`", agglayer_path.display()))?;

    Ok(())
}

/// Resolves the path of a generated table file relative to this crate's manifest, so the
/// generator works regardless of the current working directory.
fn table_path(crate_relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../crates")
        .join(crate_relative)
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use miden_protocol::account::AccountId;
    use miden_protocol::block::FeeParameters;
    use miden_protocol::testing::account_id::ACCOUNT_ID_PUBLIC_FUNGIBLE_FAUCET;
    use miden_protocol::transaction::RawOutputNote;
    use miden_standards::note::TxFeeNote;
    use miden_tx::NetworkNotePricer;

    use super::*;

    /// Relative drift (in percent) tolerated between a measured cost and its checked-in
    /// constant before the snapshot check fails.
    ///
    /// Small cycle drift is continuously introduced by unrelated changes landing on the base
    /// branch (kernel tweaks, shared MASM edits); an exact-match check would force every open
    /// PR to regenerate the tables on each such change. Within the tolerance the tables stay
    /// as they are - fee-wise this is safe, since the fee is logarithmic in cycles and the
    /// pricing safety margin (one verification cycle by default, roughly a 2x cycle headroom)
    /// dwarfs the tolerated drift.
    const DRIFT_TOLERANCE_PERCENT: u64 = 5;

    /// Every priced note must price end-to-end through the pricer: each root its consumption
    /// declares as created has to resolve through the pricer's built-in lookup, or
    /// fee-schedule construction would fail at runtime with `UnknownNoteScriptRoot`.
    #[test]
    fn every_priced_note_prices_end_to_end() {
        let fee_faucet_id = AccountId::try_from(ACCOUNT_ID_PUBLIC_FUNGIBLE_FAUCET)
            .expect("testing faucet ID should be valid");
        let pricer = NetworkNotePricer::builder()
            .fee_parameters(FeeParameters::new(fee_faucet_id, 500))
            .build();

        for &note in PricedNote::all() {
            pricer
                .price(note.script_root())
                .unwrap_or_else(|err| panic!("{} cannot be priced: {err}", note.name()));
        }
    }

    /// Locks the generated doc articles: they are data, and the names an initial-letter
    /// heuristic would get wrong (vowel-sound initialisms vs. words like "REMOVE") must keep
    /// matching the checked-in tables.
    #[test]
    fn doc_subjects_use_the_checked_in_articles() {
        let subjects: BTreeMap<&str, String> =
            PricedNote::all().iter().map(|note| (note.name(), note.doc_subject())).collect();
        assert_eq!(subjects["ALLOWLIST_CONFIG"], "an ALLOWLIST_CONFIG");
        assert_eq!(subjects["BLOCKLIST_CONFIG"], "a BLOCKLIST_CONFIG");
        assert_eq!(subjects["OWNER_CONFIG"], "an OWNER_CONFIG");
        assert_eq!(subjects["UPDATE_GER"], "an UPDATE_GER");
        assert_eq!(subjects["RBAC_CONFIG"], "an RBAC_CONFIG");
        assert_eq!(subjects["REMOVE_GER"], "a REMOVE_GER");
        assert_eq!(subjects["P2ID"], "a P2ID");
    }

    /// Ties the hand-maintained created-notes metadata backing recursive pricing to actual
    /// execution: every priced scenario is executed, and the script roots of the full output
    /// notes other than the TX_FEE note must be exactly the consumed note's declared
    /// `created_notes`, so both under- and over-declaration are caught.
    #[tokio::test]
    async fn created_notes_cover_executed_output_notes() -> Result<()> {
        for &note in PricedNote::all() {
            let declared: BTreeSet<NoteScriptRoot> =
                note.note_cost().created_notes().iter().copied().collect();

            let mut observed = BTreeSet::new();
            for &bench in note.scenarios() {
                let executed = build_benchmark_context(bench).await?.execute().await?;
                for output_note in executed.output_notes().iter() {
                    let RawOutputNote::Full(created) = output_note else {
                        continue;
                    };
                    let root = created.script().root();
                    if root == TxFeeNote::script_root() {
                        continue;
                    }
                    assert!(
                        declared.contains(&root),
                        "scenario `{bench}` created a note with undeclared script root {root}",
                    );
                    observed.insert(root);
                }
            }

            assert_eq!(observed, declared, "declared created notes were not observed for {note:?}");
        }
        Ok(())
    }

    /// Snapshot check enforcing freshness of the checked-in cost tables: re-executes the
    /// benchmark scenarios of every note in [`PricedNote::all`] and compares each measured
    /// maximum against the compiled-in constant, failing when they diverge by more than
    /// [`DRIFT_TOLERANCE_PERCENT`]. Catches kernel, standards, or agglayer changes that
    /// meaningfully shift a note's consumption cost without the tables having been
    /// regenerated.
    ///
    /// Driven by [`PricedNote::all`] rather than a per-note case list, so a note cannot be
    /// added to the tables without its constant gaining a drift guard. Drift is collected
    /// across all the notes before it is asserted on, so one run reports every stale constant
    /// (a scenario that fails to execute still aborts the run immediately).
    #[tokio::test]
    async fn checked_in_cost_matches_benched_cycles() -> Result<()> {
        let mut stale = Vec::new();
        for &note in PricedNote::all() {
            let measured = benched_cycles(note).await?;
            let committed = note.committed_cycles();

            let (measured_scaled, committed) = (u64::from(measured) * 100, u64::from(committed));
            let within_tolerance = measured_scaled <= committed * (100 + DRIFT_TOLERANCE_PERCENT)
                && measured_scaled >= committed * (100 - DRIFT_TOLERANCE_PERCENT);
            if !within_tolerance {
                stale.push(format!(
                    "{}: measured {measured} cycles vs checked-in {committed}",
                    note.name(),
                ));
            }
        }

        assert!(
            stale.is_empty(),
            "cost table stale for {} note(s), each more than {DRIFT_TOLERANCE_PERCENT}% from \
             its checked-in constant: {}. Run `make update-note-costs` and commit the updated \
             tables",
            stale.len(),
            stale.join("; "),
        );
        Ok(())
    }

    /// Guards the hand-maintained [`PricedNote::all`] slice: every network-account consumption
    /// scenario must contribute to exactly one priced note, so a scenario added to
    /// [`ExecutionBenchmark`] without a [`PricedNote`] mapping (or a variant omitted from
    /// [`PricedNote::all`]) fails here.
    #[test]
    fn every_priced_scenario_is_covered_exactly_once() {
        let mut priced_scenarios: Vec<ExecutionBenchmark> = PricedNote::all()
            .iter()
            .flat_map(|note| note.scenarios().iter().copied())
            .collect();
        let unpriced: Vec<ExecutionBenchmark> = ExecutionBenchmark::all()
            .iter()
            .copied()
            .filter(|bench| !priced_scenarios.contains(bench))
            .collect();

        // The signature-auth wallet scenarios (including the sponsor-side FEE_SPONSORSHIP
        // reclaim) and the zero-fee agglayer scenarios do not price any note; everything else
        // must.
        let expected_unpriced = [
            ExecutionBenchmark::ConsumeSingleP2IDFalcon,
            ExecutionBenchmark::ConsumeSingleP2IDEcdsa,
            ExecutionBenchmark::ConsumeTwoP2IDFalcon,
            ExecutionBenchmark::ConsumeTwoP2IDEcdsa,
            ExecutionBenchmark::CreateSingleP2IDFalcon,
            ExecutionBenchmark::CreateSingleP2IDEcdsa,
            ExecutionBenchmark::ConsumeClaimNoteL1ToMiden,
            ExecutionBenchmark::ConsumeClaimNoteL2ToMiden,
            ExecutionBenchmark::ConsumeB2AggNote,
            ExecutionBenchmark::ConsumeB2AggNotePopulated2p31,
            ExecutionBenchmark::ConsumeB2AggNotePopulated2p31m1,
            ExecutionBenchmark::ConsumeFeeSponsorshipReclaim,
        ];
        assert_eq!(unpriced, expected_unpriced, "unexpected unpriced benchmark scenarios");

        let num_priced = priced_scenarios.len();
        priced_scenarios.sort();
        priced_scenarios.dedup();
        assert_eq!(num_priced, priced_scenarios.len(), "a scenario prices more than one note");
    }
}
